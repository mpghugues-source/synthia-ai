-- Synthia 003: connections to other AIs (user's own API keys), personal API tokens for Claude Code / MCP,
-- AI video generations, imported videos.

-- API keys each user brings for Claude (Anthropic), ChatGPT (OpenAI), Gemini (Google), Kling AI…
-- Encrypted with SOCIAL_TOKEN_KEY (AES-256-GCM), never sent back to the browser.
CREATE TABLE IF NOT EXISTS ai_connections (
  id            INT          NOT NULL AUTO_INCREMENT PRIMARY KEY,
  user_id       INT          NOT NULL,
  provider      VARCHAR(20)  NOT NULL,
  key_enc       TEXT         NOT NULL,
  key_hint      VARCHAR(16)  NULL,          -- last 4 characters, to recognise the key
  text_model    VARCHAR(120) NULL,
  video_model   VARCHAR(120) NULL,
  models_json   TEXT         NULL,          -- models the key gives access to (from the provider's list)
  created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_used_at  DATETIME     NULL,
  UNIQUE KEY uq_ai_user_provider (user_id, provider),
  CONSTRAINT fk_ai_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Personal access tokens (Claude Code, MCP clients, scripts). Only the SHA-256 of the token is stored.
CREATE TABLE IF NOT EXISTS api_tokens (
  id            INT          NOT NULL AUTO_INCREMENT PRIMARY KEY,
  user_id       INT          NOT NULL,
  name          VARCHAR(80)  NOT NULL,
  token_hash    CHAR(64)     NOT NULL,
  prefix        VARCHAR(16)  NOT NULL,
  created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_used_at  DATETIME     NULL,
  revoked_at    DATETIME     NULL,
  UNIQUE KEY uq_token_hash (token_hash),
  KEY ix_token_user (user_id),
  CONSTRAINT fk_token_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Videos generated by an external AI (Kling, Veo…) for a project.
CREATE TABLE IF NOT EXISTS ai_generations (
  id            INT          NOT NULL AUTO_INCREMENT PRIMARY KEY,
  user_id       INT          NOT NULL,
  project_id    VARCHAR(64)  NOT NULL,
  provider      VARCHAR(20)  NOT NULL,
  model         VARCHAR(120) NULL,
  external_id   VARCHAR(255) NULL,
  prompt        TEXT         NOT NULL,
  status        ENUM('queued','running','succeeded','failed') NOT NULL DEFAULT 'queued',
  error         VARCHAR(500) NULL,
  created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY ix_gen_status (status),
  CONSTRAINT fk_gen_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- New project origins: a video imported (made with Claude Code, Higgsfield, CapCut…) or generated by an external AI.
ALTER TABLE projects MODIFY COLUMN mode ENUM('ai','manual','narration','import','generated') NOT NULL DEFAULT 'ai';
ALTER TABLE projects ADD COLUMN IF NOT EXISTS source VARCHAR(40) NULL;

-- Sign in / sign up with Google (Gmail), Facebook, Instagram or X: external identity linked to a Synthia user.
CREATE TABLE IF NOT EXISTS auth_identities (
  id          INT          NOT NULL AUTO_INCREMENT PRIMARY KEY,
  user_id     INT          NOT NULL,
  provider    VARCHAR(20)  NOT NULL,
  subject     VARCHAR(128) NOT NULL,
  created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_identity (provider, subject),
  KEY ix_identity_user (user_id),
  CONSTRAINT fk_identity_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Studio projects that stay (like conversations in Claude, ChatGPT, Gemini): autosaved work in progress,
-- listed under "Recent" and resumable at any time.
CREATE TABLE IF NOT EXISTS studio_drafts (
  id          CHAR(36)     NOT NULL PRIMARY KEY,
  user_id     INT          NOT NULL,
  title       VARCHAR(255) NULL,
  mode        VARCHAR(20)  NOT NULL DEFAULT 'ai',
  state_json  MEDIUMTEXT   NOT NULL,
  project_id  VARCHAR(64)  NULL,
  created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY ix_drafts_user (user_id, updated_at),
  CONSTRAINT fk_draft_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Quality control at 100 % (grammar, pronunciation, clear voice) and the creator's approval before any publication.
ALTER TABLE projects ADD COLUMN IF NOT EXISTS qa_status VARCHAR(20) NULL;      -- running | passed | failed | manual
ALTER TABLE projects ADD COLUMN IF NOT EXISTS qa_report MEDIUMTEXT NULL;
ALTER TABLE projects ADD COLUMN IF NOT EXISTS approved_at DATETIME NULL;

-- Phonetic lexicon per user: how the VOICE must say a word (applied to the spoken text only; subtitles keep the spelling).
CREATE TABLE IF NOT EXISTS voice_lexicon (
  id          INT          NOT NULL AUTO_INCREMENT PRIMARY KEY,
  user_id     INT          NOT NULL,
  lang        VARCHAR(5)   NOT NULL,
  word        VARCHAR(80)  NOT NULL,
  spoken      VARCHAR(160) NOT NULL,
  created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_lexicon (user_id, lang, word),
  CONSTRAINT fk_lexicon_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
